export function assignBestLineup(players: Player[], formation: FormationId): Player[] {
  const slots = FORMATIONS[formation];
  const available = players.filter((p) => p.suspended === 0 && p.injured === 0);
  const pickedIds = new Set<string>();
  const slotAssignment = new Map<string, number>();

  // Escolhe o melhor jogador compatível para cada slot
  for (const slot of slots) {
    let best: Player | undefined;
    let bestScore = -999;
    for (const p of available) {
      if (pickedIds.has(p.id)) continue;
      const samePos = p.pos === slot.reqPos;
      const gPenalty = (p.pos === 'G') !== (slot.reqPos === 'G') ? -60 : 0;
      const posBonus = samePos ? 18 : 0;
      const energyFactor = p.energy / 100;
      const score = p.ovr * energyFactor + posBonus + gPenalty;
      if (score > bestScore) {
        bestScore = score;
        best = p;
      }
    }
    if (best) {
      pickedIds.add(best.id);
      slotAssignment.set(best.id, slot.index);
    }
  }

  return players.map((p) => {
    if (slotAssignment.has(p.id)) {
      return { ...p, isStarter: true, slotIndex: slotAssignment.get(p.id) };
    }
    return { ...p, isStarter: false, slotIndex: undefined };
  });
}

export function buildInitialDatabase(): { clubs: Club[]; players: Player[] } {
  const clubs: Club[] = [];
  const allPlayers: Player[] = [];
  let pidCounter = 1;

  for (const rc of RAW_CLUBS) {
    const clubPlayers: Player[] = rc.roster.map(([name, pos, age, ovr, t1, t2, star]) => {
      const id = `p_${pidCounter++}`;
      return {
        id,
        name: name.trim(),
        pos,
        age,
        ovr,
        traits: [t1, t2],
        star: !!star,
        energy: 100,
        morale: 80,
        yellowCards: 0,
        suspended: 0,
        injured: 0,
        goals: 0,
        assists: 0,
        matches: 0,
        wage: calcWage(ovr, star),
        value: calcMarketValue(ovr, age, star),
        clubId: rc.id,
        isStarter: false,
      };
    });

    const linedUp = assignBestLineup(clubPlayers, rc.formation);
    allPlayers.push(...linedUp);

    const starters = linedUp.filter((p) => p.isStarter);
    const bestLeader = [...starters].sort((a, b) => b.ovr + b.age * 0.25 - (a.ovr + a.age * 0.25))[0];
    const bestFK =
      [...starters].find((p) => p.traits.includes('Falta')) ||
      [...starters].sort((a, b) => b.ovr - a.ovr)[0];

    const defaultTicket =
      rc.division === 'A' ? (rc.fanbase >= 85 ? 70 : 50) : rc.fanbase >= 70 ? 40 : 30;

    clubs.push({
      id: rc.id,
      name: rc.name,
      shortName: rc.shortName,
      abbr: rc.abbr,
      state: rc.state,
      division: rc.division,
      primaryColor: rc.primaryColor,
      secondaryColor: rc.secondaryColor,
      accentColor: rc.accentColor,
      pattern: rc.pattern,
      stadium: rc.stadium,
      capacity: rc.capacity,
      cash: rc.cash,
      sponsorName: rc.sponsorName,
      sponsorPerRound: rc.sponsorPerRound,
      fanbase: rc.fanbase,
      youthLevel: rc.youthLevel,
      coachName: rc.coachName,
      tactics: {
        formation: rc.formation,
        style: 'Equilibrado',
        passing: 'Misto',
        marking: 'Normal',
        captainId: bestLeader?.id,
        setPieceId: bestFK?.id,
        ticketPrice: defaultTicket,
      },
    });
  }

  for (const [name, pos, age, ovr, t1, t2, star] of FREE_AGENTS) {
    allPlayers.push({
      id: `p_${pidCounter++}`,
      name,
      pos,
      age,
      ovr,
      traits: [t1, t2],
      star: !!star,
      energy: 100,
      morale: 75,
      yellowCards: 0,
      suspended: 0,
      injured: 0,
      goals: 0,
      assists: 0,
      matches: 0,
      wage: calcWage(ovr, star),
      value: 0, // passe livre!
      clubId: 'FREE',
      isStarter: false,
    });
  }

  return { clubs, players: allPlayers };
}
